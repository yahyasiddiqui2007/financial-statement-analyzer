"""Generates the AI financial analysis with Claude.

Flow: normalized history → evidence pack → Claude (structured JSON output) →
claim validation → AIAnalysis. The model never sees raw filings or the
internet; it sees only the evidence pack built from this app's own metrics.
"""

from __future__ import annotations

from collections.abc import Callable
from dataclasses import dataclass
from datetime import UTC, datetime
from typing import Final, Literal

import anthropic
from anthropic.types.beta import BetaMessageParam, BetaOutputConfigParam
from pydantic import ValidationError

from fsa.ai.evidence import EvidencePack, build_evidence_pack
from fsa.ai.validation import (
    MAX_CLAIMS_PER_SECTION,
    OUTPUT_SCHEMA,
    Claim,
    RawAnalysis,
    RejectedClaim,
    Section,
    validate_claims,
)
from fsa.ingestion import FinancialHistory

MODEL = "claude-opus-5-5"
# Claude Opus 5.5's default effort is "medium"; set explicitly so the choice is visible.
EFFORT: Final[Literal["medium"]] = "medium"
MAX_TOKENS = 16000

DISCLAIMER = (
    "Educational analysis generated by an AI model from this app's calculated metrics. "
    "It is not financial or investment advice and may contain errors. It does not consider "
    "any information outside the figures shown here. Check each claim against its cited "
    "figures and the original SEC filings."
)

SYSTEM_PROMPT = f"""\
You write educational financial-statement analysis for a student learning finance. You will \
receive a JSON evidence list for one company. Each evidence item has an id, a label, an \
optional fiscal period, and a pre-formatted value. Trend items describe multi-year changes.

Produce four sections:
- strengths: financial strengths the evidence shows
- concerns: potential concerns the evidence shows
- trends: the most important multi-year trends
- questions: questions an analyst should investigate in the company's filings, each phrased \
as a question and motivated by the cited evidence

Rules that every item must follow:
1. Use only the evidence list. Do not use outside knowledge about the company, its industry, \
products, competitors, management, news, stock price, valuation, or the economy.
2. Cite every evidence id that supports the item in evidence_ids. Cite only ids that appear \
in the list.
3. Copy numbers exactly as they are written in the cited evidence, including units \
(for example "46.9%", "$416,161M", "1.34x", "FY2025"). Do not calculate, round, convert or \
estimate any new number, and do not write numbers that are not in the cited evidence.
4. If a value is "not available" or "not reported", you may say so, but do not guess it.
5. Describe the financial statements only. Do not give investment advice or opinions about \
the stock: no buy, sell or hold language, no valuation views, no predictions of returns.
6. Write plain, specific sentences. One idea per item. Include between 2 and \
{MAX_CLAIMS_PER_SECTION} items per section when the evidence supports them, and fewer if it \
does not.
"""


class AIUnavailableError(Exception):
    """AI analysis can't run here (e.g. no Anthropic credentials configured)."""


class AIServiceError(Exception):
    """The AI service failed or returned something unusable."""


@dataclass(frozen=True, slots=True)
class CompletionResult:
    text: str  # the model's JSON output
    model: str  # the model that actually answered (a fallback model, if one was used)


# (system prompt, user content) → model output. Swappable so tests never call the API.
Completer = Callable[[str, str], CompletionResult]


@dataclass(frozen=True, slots=True)
class AIAnalysis:
    company_ticker: str
    model: str
    generated_at: datetime
    sections: dict[Section, tuple[Claim, ...]]
    rejected: tuple[RejectedClaim, ...]
    evidence_count: int
    disclaimer: str = DISCLAIMER


class ClaudeCompleter:
    """Calls Claude with a strict JSON schema so the reply always has the expected shape."""

    def __init__(self, client: anthropic.Anthropic | None = None) -> None:
        self._client = client

    def _get_client(self) -> anthropic.Anthropic:
        if self._client is None:
            try:
                # Reads ANTHROPIC_API_KEY (or another configured Anthropic credential).
                client = anthropic.Anthropic()
            except anthropic.AnthropicError as exc:
                raise AIUnavailableError(_NOT_CONFIGURED) from exc
            # The SDK only complains about missing credentials once a request is sent,
            # so check up front and give a clear message instead.
            if client.api_key is None and client.auth_token is None and client.credentials is None:
                raise AIUnavailableError(_NOT_CONFIGURED)
            self._client = client
        return self._client

    def __call__(self, system: str, user: str) -> CompletionResult:
        client = self._get_client()
        output_config: BetaOutputConfigParam = {
            "effort": EFFORT,
            "format": {"type": "json_schema", "schema": OUTPUT_SCHEMA},
        }
        messages: list[BetaMessageParam] = [{"role": "user", "content": user}]
        try:
            response = client.beta.messages.create(
                model=MODEL,
                max_tokens=MAX_TOKENS,
                # If the request is declined by a safety classifier, the API retries it
                # on a fallback model chosen for that case, within the same call.
                betas=["server-side-fallback-2026-07-01"],
                fallbacks="default",
                output_config=output_config,
                system=system,
                messages=messages,
            )
        except anthropic.CredentialsError as exc:
            raise AIUnavailableError(_NOT_CONFIGURED) from exc
        except anthropic.AuthenticationError as exc:
            raise AIUnavailableError("The Anthropic API key was rejected.") from exc
        except anthropic.RateLimitError as exc:
            raise AIServiceError("The AI service is busy. Try again in a minute.") from exc
        except anthropic.APIStatusError as exc:
            raise AIServiceError(f"The AI service returned an error ({exc.status_code}).") from exc
        except anthropic.APIConnectionError as exc:
            raise AIServiceError("Could not reach the AI service.") from exc

        if response.stop_reason == "refusal":
            raise AIServiceError("The AI model declined to analyze this data.")
        if response.stop_reason == "max_tokens":
            raise AIServiceError("The AI response was cut off before it finished.")
        text = next((b.text for b in response.content if b.type == "text"), None)
        if text is None:
            raise AIServiceError("The AI response contained no analysis.")
        return CompletionResult(text=text, model=response.model)


_NOT_CONFIGURED = (
    "No Anthropic API key was found. Set the ANTHROPIC_API_KEY environment variable and "
    "restart the server."
)


def generate_analysis(
    history: FinancialHistory,
    complete: Completer,
    *,
    now: Callable[[], datetime] = lambda: datetime.now(UTC),
) -> AIAnalysis:
    pack: EvidencePack = build_evidence_pack(history)
    result = complete(SYSTEM_PROMPT, pack.to_prompt_json())
    try:
        raw = RawAnalysis.model_validate_json(result.text)
    except ValidationError as exc:
        raise AIServiceError("The AI response was not in the expected format.") from exc

    checked = validate_claims(raw, pack)
    return AIAnalysis(
        company_ticker=history.company.ticker,
        model=result.model,
        generated_at=now(),
        sections=checked.sections,
        rejected=checked.rejected,
        evidence_count=len(pack.items),
    )

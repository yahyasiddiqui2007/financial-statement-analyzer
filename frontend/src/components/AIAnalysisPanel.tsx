import { useEffect, useRef, useState } from "react";
import { ApiError, requestAIAnalysis } from "../api/client";
import type { AIAnalysis, AIClaim, AIEvidence, AISection } from "../api/types";
import { formatTimestamp } from "../lib/format";

type State =
  | { status: "idle" }
  | { status: "loading" }
  | { status: "success"; analysis: AIAnalysis }
  | { status: "error"; error: ApiError };

const SECTIONS: { key: AISection; title: string; empty: string }[] = [
  { key: "strengths", title: "Financial strengths", empty: "No strengths passed verification." },
  { key: "concerns", title: "Potential concerns", empty: "No concerns passed verification." },
  { key: "trends", title: "Important trends", empty: "No trends passed verification." },
  {
    key: "questions",
    title: "Questions to investigate",
    empty: "No questions passed verification.",
  },
];

const DISCLAIMER_PREVIEW =
  "Educational analysis generated by an AI model from this app's calculated metrics. " +
  "Not financial or investment advice.";

/**
 * On-demand AI analysis. Nothing is sent to the model until the user asks,
 * because each analysis costs money to generate.
 */
export function AIAnalysisPanel({ ticker }: { ticker: string }) {
  const [state, setState] = useState<State>({ status: "idle" });
  const controller = useRef<AbortController | null>(null);

  useEffect(() => () => controller.current?.abort(), []);

  const generate = async () => {
    controller.current?.abort();
    controller.current = new AbortController();
    setState({ status: "loading" });
    try {
      const analysis = await requestAIAnalysis(ticker, controller.current.signal);
      setState({ status: "success", analysis });
    } catch (err) {
      if (err instanceof DOMException && err.name === "AbortError") return;
      setState({
        status: "error",
        error: err instanceof ApiError ? err : new ApiError("unknown", "Something went wrong."),
      });
    }
  };

  return (
    <section className="panel ai" aria-labelledby="ai-heading" aria-busy={state.status === "loading"}>
      <div className="section-head">
        <h2 id="ai-heading" className="section-title">
          AI analysis
        </h2>
        <span className="ai__badge">Educational · not advice</span>
      </div>

      <p className="ai__disclaimer" role="note">
        {state.status === "success" ? state.analysis.disclaimer : DISCLAIMER_PREVIEW}
      </p>

      {state.status === "idle" && (
        <div className="ai__intro">
          <p>
            Claude reviews only the metrics and trends calculated on this page and writes
            strengths, concerns, trends and questions for {ticker}. Every claim must cite the
            figures it relies on, and each one is checked against those figures before it is shown.
          </p>
          <button type="button" className="button" onClick={generate}>
            Generate AI analysis
          </button>
        </div>
      )}

      {state.status === "loading" && (
        <p className="loading__status" role="status">
          <span className="spinner" aria-hidden="true" />
          Claude is reviewing {ticker}'s metrics. This can take up to a minute…
        </p>
      )}

      {state.status === "error" && <AIError error={state.error} onRetry={generate} />}

      {state.status === "success" && <AIResult analysis={state.analysis} />}
    </section>
  );
}

function AIError({ error, onRetry }: { error: ApiError; onRetry: () => void }) {
  return (
    <div className="ai__error" role="alert">
      <p className="error__title">
        {error.code === "ai_not_configured" ? "AI analysis is not configured" : "AI analysis failed"}
      </p>
      <p className="error__message">{error.message}</p>
      {error.code === "ai_not_configured" ? (
        <p className="error__hint">
          Add an Anthropic API key, then restart the server:{" "}
          <code>export ANTHROPIC_API_KEY=…</code>
        </p>
      ) : (
        <button type="button" className="button" onClick={onRetry}>
          Try again
        </button>
      )}
    </div>
  );
}

function AIResult({ analysis }: { analysis: AIAnalysis }) {
  const accepted = SECTIONS.reduce((n, s) => n + analysis[s.key].length, 0);
  return (
    <>
      <p className="ai__meta">
        Generated by <code>{analysis.model}</code> on {formatTimestamp(analysis.generated_at)} from{" "}
        {analysis.evidence_count} facts. {accepted} claim{accepted === 1 ? "" : "s"} passed
        verification
        {analysis.rejected.length > 0 && `, ${analysis.rejected.length} removed`}.
      </p>
      <div className="ai__sections">
        {SECTIONS.map((section) => (
          <div key={section.key} className="ai__section">
            <h3 className="ai__section-title">{section.title}</h3>
            {analysis[section.key].length === 0 ? (
              <p className="ai__empty">{section.empty}</p>
            ) : (
              <ol className="claims">
                {analysis[section.key].map((claim, i) => (
                  <ClaimItem key={i} claim={claim} />
                ))}
              </ol>
            )}
          </div>
        ))}
      </div>
      {analysis.rejected.length > 0 && (
        <details className="ai__rejected">
          <summary>
            {analysis.rejected.length} claim{analysis.rejected.length === 1 ? " was" : "s were"}{" "}
            removed because they could not be verified
          </summary>
          <ul>
            {analysis.rejected.map((r, i) => (
              <li key={i}>
                <span className="ai__rejected-statement">“{r.statement}”</span>
                <span className="ai__rejected-reason">
                  {r.section}: {r.reason}
                </span>
              </li>
            ))}
          </ul>
        </details>
      )}
    </>
  );
}

function ClaimItem({ claim }: { claim: AIClaim }) {
  return (
    <li className="claim">
      <p className="claim__statement">{claim.statement}</p>
      <ul className="evidence" aria-label="Supporting figures">
        {claim.evidence.map((e) => (
          <EvidenceChip key={e.id} evidence={e} />
        ))}
      </ul>
    </li>
  );
}

function EvidenceChip({ evidence }: { evidence: AIEvidence }) {
  const isSentence = evidence.kind === "trend";
  const tooltip = [evidence.id, isSentence ? evidence.value : null, evidence.note]
    .filter(Boolean)
    .join("\n");
  return (
    <li className="evidence__chip" title={tooltip}>
      <span className="evidence__label">
        {evidence.label}
        {evidence.period && ` · ${evidence.period}`}
      </span>
      {!isSentence && <span className="evidence__value">{evidence.value}</span>}
    </li>
  );
}
